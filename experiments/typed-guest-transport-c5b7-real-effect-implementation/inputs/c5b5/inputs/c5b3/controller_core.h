#ifndef CAPSULE_C5B3_CONTROLLER_CORE_H
#define CAPSULE_C5B3_CONTROLLER_CORE_H

#include <stdint.h>

/*
 * This is a pure state machine. It has no entry point, I/O, process, libkrun,
 * Hypervisor, filesystem, clock, allocation, or durable-store implementation.
 * A future adapter must translate requested actions into effects only after an
 * exact, separately authorized run profile has been verified.
 */

enum c5b3_state {
    C5B3_STATE_STOPPED = 0,
    C5B3_STATE_BOUND = 1,
    C5B3_STATE_ENDPOINTS_READY = 2,
    C5B3_STATE_RUNNER_READY = 3,
    C5B3_STATE_INPUT_TRANSFER = 4,
    C5B3_STATE_LAUNCHER_VALIDATED = 5,
    C5B3_STATE_CHILD_RUNNING = 6,
    C5B3_STATE_RESULT_VALIDATED = 7,
    C5B3_STATE_TRAILER_WRITTEN = 8,
    C5B3_STATE_FRAME_OBSERVED = 9,
    C5B3_STATE_TERMINAL_PROOF = 10,
    C5B3_STATE_DURABLE_COMMIT = 11,
    C5B3_STATE_COMPLETE = 12,
    C5B3_STATE_TEARDOWN = 13,
    C5B3_STATE_ABSENCE_PROVEN = 14,
    C5B3_STATE_CLEANUP_REQUIRED = 15,
    C5B3_STATE_REFUSED_CLEAN = 16,
    C5B3_STATE_FENCED = 17,
    C5B3_STATE_REFUSED = 18,
};

enum c5b3_event {
    C5B3_EVENT_BIND_EXACT = 1,
    C5B3_EVENT_ENDPOINTS_VERIFIED = 2,
    C5B3_EVENT_DRAINS_STARTED = 3,
    C5B3_EVENT_RUNNER_STARTED = 4,
    C5B3_EVENT_INPUTS_WRITTEN = 5,
    C5B3_EVENT_CHILD_STARTED = 6,
    C5B3_EVENT_RESULT_ACCEPTED = 7,
    C5B3_EVENT_TRAILER_COMMITTED = 8,
    C5B3_EVENT_FRAME_ACCEPTED = 9,
    C5B3_EVENT_TERMINAL_FACTS_JOINED = 10,
    C5B3_EVENT_DURABLE_COMMIT_CONFIRMED = 11,
    C5B3_EVENT_RESPONSE_DELIVERED = 12,
    C5B3_EVENT_RESPONSE_LOST = 13,
    C5B3_EVENT_TEARDOWN_CONFIRMED = 14,
    C5B3_EVENT_ABSENCE_CONFIRMED = 15,
    C5B3_EVENT_CLEANUP_CONFIRMED = 16,
    C5B3_EVENT_CANCEL = 17,
    C5B3_EVENT_DEADLINE = 18,
    C5B3_EVENT_STALL = 19,
    C5B3_EVENT_STREAM_RESET = 20,
    C5B3_EVENT_CAP_PLUS_ONE = 21,
    C5B3_EVENT_SHORT_WRITE = 22,
    C5B3_EVENT_READER_DEATH = 23,
    C5B3_EVENT_PROCESS_FAULT = 24,
    C5B3_EVENT_BINDING_MISMATCH = 25,
    C5B3_EVENT_STORE_INDETERMINATE = 26,
};

enum c5b3_fact {
    C5B3_FACT_NONE = 0,
    C5B3_FACT_EXACT_PROFILE = UINT64_C(1) << 0,
    C5B3_FACT_EXACT_AUTHORIZATION = UINT64_C(1) << 1,
    C5B3_FACT_EXACT_ARTIFACTS = UINT64_C(1) << 2,
    C5B3_FACT_FIXED_ROOT_ABSENT = UINT64_C(1) << 3,
    C5B3_FACT_ENDPOINTS_DISTINCT = UINT64_C(1) << 4,
    C5B3_FACT_DRAINS_ACTIVE = UINT64_C(1) << 5,
    C5B3_FACT_SOURCE_COMPLETE = UINT64_C(1) << 6,
    C5B3_FACT_INPUT_COMPLETE = UINT64_C(1) << 7,
    C5B3_FACT_LAUNCHER_INPUTS_VALID = UINT64_C(1) << 8,
    C5B3_FACT_RESULT_VALID = UINT64_C(1) << 9,
    C5B3_FACT_TRAILER_LAST = UINT64_C(1) << 10,
    C5B3_FACT_FRAME_EXACT = UINT64_C(1) << 11,
    C5B3_FACT_CHILD_TREE_ABSENT = UINT64_C(1) << 12,
    C5B3_FACT_RUNNER_TERMINAL = UINT64_C(1) << 13,
    C5B3_FACT_RUNNER_ABSENT = UINT64_C(1) << 14,
    C5B3_FACT_TEARDOWN_RESOLVED = UINT64_C(1) << 15,
    C5B3_FACT_CLEANUP_FALSE = UINT64_C(1) << 16,
    C5B3_FACT_DURABLE_RECORD = UINT64_C(1) << 17,
    C5B3_FACT_FIXED_ROOT_REMOVED = UINT64_C(1) << 18,
};

enum c5b3_action {
    C5B3_ACTION_NONE = 0,
    C5B3_ACTION_CREATE_ENDPOINTS = UINT64_C(1) << 0,
    C5B3_ACTION_START_DRAINS = UINT64_C(1) << 1,
    C5B3_ACTION_START_RUNNER = UINT64_C(1) << 2,
    C5B3_ACTION_WRITE_SOURCE = UINT64_C(1) << 3,
    C5B3_ACTION_WRITE_INPUT = UINT64_C(1) << 4,
    C5B3_ACTION_CLOSE_INPUT_WRITERS = UINT64_C(1) << 5,
    C5B3_ACTION_ALLOW_CHILD = UINT64_C(1) << 6,
    C5B3_ACTION_REQUEST_TEARDOWN = UINT64_C(1) << 7,
    C5B3_ACTION_PROVE_ABSENCE = UINT64_C(1) << 8,
    C5B3_ACTION_REMOVE_FIXED_ROOT = UINT64_C(1) << 9,
    C5B3_ACTION_REQUEST_DURABLE_COMMIT = UINT64_C(1) << 10,
    C5B3_ACTION_DELIVER_STORED = UINT64_C(1) << 11,
    C5B3_ACTION_REPLAY_STORED = UINT64_C(1) << 12,
    C5B3_ACTION_FENCE_STORE = UINT64_C(1) << 13,
    C5B3_ACTION_STOP_MISMATCH = UINT64_C(1) << 14,
};

enum c5b3_disposition {
    C5B3_DISPOSITION_ADVANCED = 1,
    C5B3_DISPOSITION_REFUSED = 2,
    C5B3_DISPOSITION_TEARDOWN_REQUIRED = 3,
    C5B3_DISPOSITION_REPLAY = 4,
    C5B3_DISPOSITION_FENCED = 5,
};

struct c5b3_controller {
    uint32_t state;
    uint32_t durable;
};

struct c5b3_step {
    uint32_t state;
    uint32_t disposition;
    uint64_t actions;
};

void c5b3_controller_reset(struct c5b3_controller *controller);
struct c5b3_step c5b3_controller_step(
    struct c5b3_controller *controller,
    uint32_t event,
    uint64_t facts
);

#endif
